interface Tile {
  label: string;
  value: string;
  sub: string;
  tone?: 'good' | 'bad' | 'none';
}

function tile(t: Tile): HTMLElement {
  return h(
    'div',
    { class: `sfl-tile${t.tone ? ` sfl-tile--${t.tone}` : ''}` },
    h('div', { class: 'sfl-tile__label' }, t.label),
    h('div', { class: 'sfl-tile__value sf-num' }, t.value),
    h('div', { class: 'sfl-tile__sub' }, t.sub),
  );
}

export function tiles(facts: Facts, fmt: Fmt): HTMLElement {
  const list: Tile[] = [];
  if (facts.kind === 'unique') {
    const f = facts;
    list.push({ label: 'Distance from the truth', value: fmt.dist(f.errorM), sub: 'measured against the answer key' });
    list.push({ label: 'What the fix claims', value: fmt.dist(f.sigmaRadialM), sub: '1 σ, all directions together' });
    list.push({
      label: 'Error ÷ claim',
      value: f.ratio === null ? '—' : `${times(f.ratio)}×`,
      sub: 'near 1 when the claim is honest',
      tone: f.ratio === null ? 'none' : f.ratio <= 2.5 ? 'good' : 'bad',
    });
    list.push(
      f.inside95 === null
        ? { label: 'Truth inside the 95 % ellipse?', value: 'No ellipse', sub: f.ellipseSuppressedReason ?? 'nothing to test against', tone: 'none' }
        : {
            label: 'Truth inside the 95 % ellipse?',
            value: f.inside95 ? '✓ Yes' : '✗ No',
            sub: f.inside95 ? 'as it should be about 95 times in 100' : 'the ellipse misses the answer',
            tone: f.inside95 ? 'good' : 'bad',
          },
    );
  } else if (facts.kind === 'ambiguous') {
    list.push({ label: 'Answers', value: String(facts.candidates.length), sub: 'all fit the sights' });
    list.push({ label: 'Apart', value: fmt.dist(facts.separationM), sub: 'between the candidates' });
    list.push({
      label: 'The answer key is',
      value: `Candidate ${candidateLetter(facts.nearestIndex)}`,
      sub: `${fmt.dist(facts.nearestM)} away; the sights cannot tell`,
    });
    list.push({ label: '95 % ellipse', value: 'None', sub: 'no single fix to put one round', tone: 'none' });
  } else if (facts.kind === 'underdetermined') {
    list.push({ label: 'Position', value: 'None', sub: 'one circle, not a point', tone: 'none' });
    list.push({ label: 'Circle radius', value: `${new Intl.NumberFormat('en-GB', { maximumFractionDigits: 0 }).format(facts.radiusNm)} NM`, sub: fmt.dist(facts.radiusM) });
    list.push({ label: 'The answer key is', value: 'On the circle', sub: `${fmt.dist(facts.truthOffCircleM)} from it` });
    list.push({ label: '95 % ellipse', value: 'None', sub: 'no point to put one round', tone: 'none' });
  } else {
    list.push({ label: 'Answer', value: 'None', sub: facts.reason, tone: 'bad' });
  }
  return h('div', { class: 'sfl-tiles' }, ...list.map(tile));
}

