// The figure

let figureSeq = 0;

export interface FigureEnv {
  fmt: () => Fmt;
  land: () => Promise<LandRings>;
  /** Present when the explorer's map can take overlays. */
  showOnMap?: (model: ChartModel) => void;
}

export interface Figure {
  el: HTMLElement;
  /** Resolves once the picture (and the globe's land, when shown) is drawn. */
  ready: Promise<void>;
  destroy(): void;
}

function observeWidth(el: HTMLElement, onWidth: (w: number) => void): () => void {
  let last = -1;
  const report = (w: number): void => {
    const width = Math.floor(w);
    if (width > 0 && width !== last) {
      last = width;
      onWidth(width);
    }
  };
  if (typeof ResizeObserver === 'undefined') {
    const on = (): void => report(el.clientWidth);
    window.addEventListener('resize', on);
    on();
    return () => window.removeEventListener('resize', on);
  }
  const ro = new ResizeObserver((entries) => {
    for (const e of entries) report(e.contentRect.width);
  });
  ro.observe(el);
  report(el.clientWidth);
  return () => ro.disconnect();
}

/**
 * A container that draws `render(width)` at its own width, again whenever that changes,
 * and stops listening once it has left the page.
 */
export function responsive(cls: string, render: (width: number) => Element | null): HTMLElement {
  const el = h('div', { class: cls });
  let last = -1;
  const draw = (w: number): void => {
    const width = Math.floor(w);
    if (width <= 0 || width === last) return;
    last = width;
    const node = render(width);
    el.replaceChildren(...(node ? [node] : []));
  };
  if (typeof ResizeObserver === 'undefined') {
    requestAnimationFrame(() => draw(el.clientWidth));
    return el;
  }
  const ro = new ResizeObserver((entries) => {
    if (!el.isConnected) {
      ro.disconnect();
      return;
    }
    for (const e of entries) draw(e.contentRect.width);
  });
  ro.observe(el);
  return el;
}

/**
 * The chart for a result, with its switch between the close-up and the globe, its key,
 * and what to look at. `view` is remembered by the caller through `onView`.
 */
export function figure(
  result: FixResult,
  truth: Truth | null,
  env: FigureEnv,
  options: { view?: ChartView | null; onView?: (v: ChartView) => void; lookAt?: string; title: string },
): Figure {
  const model = chartModel(result, truth?.position ?? null);
  const uid = `sfl-fig-${++figureSeq}`;
  if (!model) {
    const el = h('div', { class: 'sfl-figure sfl-figure--empty' }, h('p', { class: 'sfl-message' }, 'Nothing to draw: the solver returned no answer.'));
    return { el, ready: Promise.resolve(), destroy: () => undefined };
  }
  let view: ChartView = options.view && (options.view === 'globe' || model.canSheet) ? options.view : model.view;
  const emphasis = result.kind === 'unique' ? emphasisFor(model, result.fix.residuals) : null;

  const plot = h('div', { class: 'sfl-figure__plot' });
  const legendSlot = h('div', { class: 'sfl-figure__legend' });
  const note = h('p', { class: 'sfl-figure__note' });
  const bar = h('div', { class: 'sfl-figure__bar' });
  const caption = h('figcaption', { class: 'sfl-figure__caption' }, options.lookAt ? h('strong', {}, 'Look at: ') : null, options.lookAt ?? '');
  const el = h('figure', { class: 'sfl-figure', id: uid }, bar, plot, note, legendSlot, caption);

  let land: LandRings | null = null;
  let landState: 'idle' | 'loading' | 'ready' | 'failed' = 'idle';
  let width = 0;
  let resolveReady: () => void = () => undefined;
  const ready = new Promise<void>((resolve) => {
    resolveReady = resolve;
  });

  const draw = (): void => {
    if (width <= 0) return;
    const drawn = renderChart(model, { width, view, fmt: env.fmt(), land, uid, emphasis });
    plot.replaceChildren(drawn.svg);
    const notes = [drawn.note, view === 'globe' && landState === 'failed' ? 'The coastlines could not be loaded, so the globe is drawn without them.' : null].filter(Boolean);
    note.textContent = notes.join(' ');
    note.hidden = notes.length === 0;
    legendSlot.replaceChildren(chartLegend(model, view));
    if (view === 'globe' && landState === 'idle') {
      landState = 'loading';
      env
        .land()
        .then((rings) => {
          land = rings;
          landState = 'ready';
        })
        .catch(() => {
          landState = 'failed';
        })
        .finally(() => {
          draw();
          resolveReady();
        });
    } else if (view === 'sheet' || landState === 'ready' || landState === 'failed') {
      resolveReady();
    }
  };

  const buttons: HTMLElement[] = [];
  if (model.canSheet) {
    const seg = h('div', { class: 'sf-seg sf-seg--sm sfl-seg', role: 'radiogroup', 'aria-label': 'Picture' });
    const opts: { v: ChartView; label: string; tip: string }[] = [
      { v: 'sheet', label: 'Close-up', tip: 'Where the lines cross: the fix, its ellipse and the answer key' },
      { v: 'globe', label: 'Whole Earth', tip: 'The same circles seen whole, with the points where each star is overhead' },
    ];
    const segButtons = opts.map((o) => {
      const b = h('button', { type: 'button', class: 'sf-seg__opt', role: 'radio', 'data-tip': o.tip, 'aria-checked': String(o.v === view) }, o.label);
      b.tabIndex = o.v === view ? 0 : -1;
      b.addEventListener('click', () => {
        if (view === o.v) return;
        view = o.v;
        segButtons.forEach((x, i) => {
          x.setAttribute('aria-checked', String(opts[i]!.v === view));
          x.tabIndex = opts[i]!.v === view ? 0 : -1;
        });
        options.onView?.(view);
        draw();
      });
      b.addEventListener('keydown', (e) => {
        if (e.key !== 'ArrowLeft' && e.key !== 'ArrowRight') return;
        e.preventDefault();
        const next = segButtons[(segButtons.indexOf(b) + 1) % segButtons.length]!;
        next.focus();
        next.click();
      });
      seg.append(b);
      return b;
    });
    buttons.push(seg);
  } else {
    buttons.push(h('span', { class: 'sfl-figure__view' }, model.kind === 'underdetermined' ? 'Whole Earth: the circle is thousands of kilometres across' : 'Whole Earth: the crossings are far apart'));
  }
  if (env.showOnMap) {
    buttons.push(
      button({
        label: 'Show on map',
        icon: 'map',
        size: 'sm',
        variant: 'outline',
        tip: 'Draw these circles, points and ellipse on the explorer’s map, and open it',
        onClick: () => env.showOnMap?.(model),
      }),
    );
  }
  bar.append(...buttons);

  const stop = observeWidth(plot, (w) => {
    width = w;
    draw();
  });
  return {
    el,
    ready,
    destroy: () => {
      stop();
      el.remove();
    },
  };
}

