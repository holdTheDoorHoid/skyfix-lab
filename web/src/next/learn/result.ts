function degMinText(deg: number): string {
  const sign = deg < 0 ? '−' : '';
  const a = Math.abs(deg);
  let d = Math.floor(a);
  let m = Math.round((a - d) * 600) / 10;
  if (m >= 60) {
    m -= 60;
    d += 1;
  }
  return `${sign}${d}° ${m.toFixed(1).padStart(4, '0')}′`;
}

export function correctionTable(reduced: readonly ReduceEntry[]): HTMLElement {
  const kinds = ['index_correction', 'dip', 'artificial_horizon_halving', 'refraction', 'semidiameter', 'parallax'] as const;
  const used = kinds.filter((k) =>
    reduced.some((e) => e.status === 'ok' && e.sight.corrections.steps.some((st) => st.kind === k && st.applied)),
  );
  const head = h('tr', {}, h('th', { scope: 'col' }, 'Sight'), h('th', { scope: 'col' }, 'Sextant reading'), ...used.map((k) => h('th', { scope: 'col' }, CORRECTION_LABEL[k])), h('th', { scope: 'col' }, 'Observed height'));
  const rows = reduced.map((e) => {
    if (e.status === 'error') return h('tr', {}, h('th', { scope: 'row' }, e.id), h('td', { colspan: String(used.length + 2) }, `Rejected: ${e.message}`));
    const c = e.sight.corrections;
    return h(
      'tr',
      {},
      h('th', { scope: 'row' }, `${e.sight.id} · ${e.sight.body}`),
      h('td', { class: 'sf-num' }, degMinText(c.input_deg)),
      ...used.map((k) => {
        const st = c.steps.find((x) => x.kind === k);
        return h('td', { class: 'sf-num' }, st && st.applied ? arcmin(st.delta_arcmin) : '—');
      }),
      h('td', { class: 'sf-num' }, degMinText(c.ho_deg)),
    );
  });
  return h(
    'div',
    { class: 'sfl-table-wrap' },
    h('table', { class: 'sf-table sfl-table' }, h('caption', {}, 'The correction chain, step by step (signed: + raises the altitude, − lowers it)'), h('thead', {}, head), h('tbody', {}, ...rows)),
  );
}

