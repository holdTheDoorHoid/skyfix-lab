const KIND_TEXT: Record<FixResult['kind'], string> = {
  unique: 'Unique fix',
  ambiguous: 'Ambiguous',
  underdetermined: 'Underdetermined',
  failed: 'Failed',
};

/** The result kind in words, never only in colour. */
export function kindChip(result: FixResult): HTMLElement {
  const extra =
    result.kind === 'ambiguous'
      ? ` · ${result.candidates.length} candidates, none preferred`
      : result.kind === 'underdetermined'
        ? ' · no position'
        : result.kind === 'unique'
          ? ''
          : ' · no answer';
  const iconName = result.kind === 'unique' ? 'target' : result.kind === 'failed' ? 'caution' : 'help';
  return h('span', { class: `sfl-kind sfl-kind--${result.kind}` }, icon(iconName), h('span', {}, `${KIND_TEXT[result.kind]}${extra}`));
}

