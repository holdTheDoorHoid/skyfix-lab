export function numbersList(result: FixResult, facts: Facts, fmt: Fmt): HTMLElement {
  const rows: HTMLElement[] = [];
  if (result.kind === 'unique' && facts.kind === 'unique') {
    const f = result.fix;
    rows.push(row('Fix', fmt.pos(f.position)));
    rows.push(row('Truth (answer key)', fmt.pos(facts.truth), 'sfl-kv--truth'));
    rows.push(row('Fix − truth', `${fmt.dist(facts.errorM)} · north ${fmt.dist(facts.errorNorthM)}, east ${fmt.dist(facts.errorEastM)}`));
    rows.push(row('Latitude, longitude change', `${signedDeg(facts.dLatDeg, 6)}, ${signedDeg(facts.dLonDeg, 6)}`));
    rows.push(row('1 σ north, east', `${fmt.dist(f.sigma_north_m)}, ${fmt.dist(f.sigma_east_m)}`));
    if (f.clock_sigma_east_m > 0) rows.push(row('Of which from the clock (east)', fmt.dist(f.clock_sigma_east_m)));
    rows.push(
      row(
        '95 % ellipse',
        f.ellipse95
          ? `${ellipseSize(f.ellipse95, fmt)} (semi-axes), major axis ${f.ellipse95.orientation_deg.toFixed(1)}° true — ${f.ellipse95.model}`
          : `not drawn: ${f.ellipse_suppressed_reason ?? 'suppressed'}`,
      ),
    );
    rows.push(row('Mahalanobis distance of the truth', facts.mahalanobis === null ? '—' : `${facts.mahalanobis.toFixed(2)} (the 95 % edge is 2.45)`));
    rows.push(row('Condition number', `${conditionText(f.conditioning.condition_number)} (rank ${f.conditioning.rank}; singular values ${f.conditioning.singular_values.map((v) => v.toPrecision(3)).join(', ')})`));
    rows.push(
      row(
        'Geometric dilution',
        f.conditioning.geometric_dilution_m_per_arcmin === null
          ? 'singular (no finite value)'
          : `${fmt.dist(f.conditioning.geometric_dilution_m_per_arcmin)} of position per arcminute of altitude noise`,
      ),
    );
    rows.push(row('Largest gap between bearings', `${f.conditioning.max_azimuth_gap_deg.toFixed(1)}°`));
    rows.push(row('Fit', `χ² ${f.chi2.toFixed(2)} on ${f.dof} degree${f.dof === 1 ? '' : 's'} of freedom, ${f.converged ? 'converged' : 'NOT converged'} after ${f.iterations} iteration${f.iterations === 1 ? '' : 's'}`));
    if (f.shared_bias_arcmin !== null) rows.push(row('Estimated shared bias', arcmin(f.shared_bias_arcmin)));
    if (f.robust) rows.push(row('Robust weighting', `Huber k = ${f.robust.huber_k}; downweighted: ${f.robust.downweighted_ids.join(', ') || 'none'}`));
    if (result.alternatives.length) {
      rows.push(row('Other minima (rejected)', result.alternatives.map((a) => `${fmt.pos(a.position)} (Δχ² ${a.delta_chi2_from_best.toFixed(1)})`).join('; ')));
    }
  } else if (result.kind === 'ambiguous') {
    result.candidates.forEach((c, i) => rows.push(row(`Candidate ${candidateLetter(i)}`, `${fmt.pos(c.position)} · χ² ${c.chi2.toExponential(1)}, Δχ² ${c.delta_chi2_from_best.toExponential(1)}`)));
    rows.push(row('Truth (answer key)', fmt.pos(facts.truth), 'sfl-kv--truth'));
  } else if (result.kind === 'underdetermined') {
    rows.push(row('Reason', result.reason));
    for (const c of result.circles) {
      rows.push(row(`${c.id} · ${c.body}`, `overhead at ${fmt.pos(c.gp)}; radius ${c.zenith_distance_deg.toFixed(4)}° = ${new Intl.NumberFormat('en-GB', { maximumFractionDigits: 1 }).format(c.zenith_distance_deg * 60)} NM`));
    }
    rows.push(row('Truth (answer key)', fmt.pos(facts.truth), 'sfl-kv--truth'));
  } else if (result.kind === 'failed') {
    rows.push(row('Reason', result.reason));
  }
  return h('dl', { class: 'sfl-numbers' }, ...rows);
}

/** The simulation's answer key, as the truth document states it. */
export function answerKey(truth: Truth, fmt: Fmt): HTMLElement {
  return h(
    'section',
    { class: 'sfl-key', 'aria-label': 'Answer key' },
    h('div', { class: 'sfl-key__head' }, icon('target'), h('h3', { class: 'sfl-h3' }, 'Answer key'), simulatedBadge()),
    h(
      'dl',
      { class: 'sfl-numbers' },
      row('True position', fmt.pos(truth.position), 'sfl-kv--truth'),
      row('Seed', String(truth.seed)),
      row('Clock offset added', `${truth.clock_offset_s} s`),
      row('Shared altitude bias added', arcmin(truth.shared_altitude_bias_arcmin, 1)),
      row('Deliberately wrong sights', truth.wrong_sight_ids.length ? truth.wrong_sight_ids.join(', ') : 'none'),
    ),
    truth.notes ? h('p', { class: 'sfl-muted' }, truth.notes) : null,
    h('p', { class: 'sfl-muted' }, 'The answer key is kept beside the session and never given to the solver.'),
  );
}
